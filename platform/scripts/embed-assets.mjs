#!/usr/bin/env node
// Package dist/ into one module the Worker imports (.generated/embedded-assets.mjs).
// Static email previews (dist/email) are left out: the dashboard renders previews on demand.
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const TEXT = new Set(['html', 'css', 'js', 'mjs', 'json', 'xml', 'txt', 'svg']);
const SKIP = [/^\/email\//];

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p))); else out.push(p);
  }
  return out;
}
const files = {};
for (const file of (await walk(DIST)).sort()) {
  const rel = '/' + path.relative(DIST, file).split(path.sep).join('/');
  if (SKIP.some((re) => re.test(rel))) continue;
  const buf = await readFile(file);
  const hash = createHash('sha256').update(buf).digest('hex').slice(0, 16);
  files[rel] = TEXT.has(rel.slice(rel.lastIndexOf('.') + 1)) ? { hash, text: buf.toString('utf8') } : { hash, b64: buf.toString('base64') };
}
const src = '// Generated by scripts/embed-assets.mjs. Do not edit.\nexport const FILES = ' + JSON.stringify(files) + ';\n';
await mkdir(path.join(ROOT, '.generated'), { recursive: true });
await writeFile(path.join(ROOT, '.generated', 'embedded-assets.mjs'), src);
const gz = gzipSync(src).length;
console.log(`Packaged ${Object.keys(files).length} files: ${(src.length / 1048576).toFixed(2)} MB, ${(gz / 1048576).toFixed(2)} MB gzipped (Workers free limit: 3 MB gzipped for the whole script).`);
if (gz > 2.7 * 1048576) { console.error('The packaged site is close to the Workers free script limit. Move to static-assets hosting (see docs/platform/HANDOFF.md).'); process.exit(1); }
